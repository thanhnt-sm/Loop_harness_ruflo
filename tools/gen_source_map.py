def tracked_files() -> list[str]:
    try:
        out = subprocess.run(
            ["git", "-C", str(ROOT), "ls-files"],
            capture_output=True, text=True, timeout=15, check=False,
        )
        if out.returncode == 0 and out.stdout.strip():
            return sorted(p for p in out.stdout.splitlines() if p.strip())
    except Exception:
        pass
    sys.stderr.write("WARN: git ls-files fail — dùng os.walk fallback\n")
    skip_dirs = {
        ".git", "node_modules", ".venv", "dist", "build", "__pycache__",
        ".pytest_cache", ".omo", ".codegraph", ".khuym", ".aide", ".clinerules",
        ".devin/loop_state", ".devin/session_state", ".devin/plan_state",
        ".devin/context_flags", ".devin/blackboard", ".devin/event_bus",
        ".devin/state", ".devin/telemetry", ".devin/artifacts",
        ".devin/agents_state", ".devin/loop_state_archive",
        ".devin/idempotency", ".devin/checkpoints", ".devin/artifact_registry",
        ".worktrees",
    }
    import os
    result = []
    for dirpath, dirnames, filenames in os.walk(ROOT):
        rel = Path(dirpath).relative_to(ROOT)
        dirnames[:] = [d for d in dirnames if str(rel / d) not in skip_dirs]
        for f in sorted(filenames):
            if f in ("package-lock.json", ".DS_Store"):
                continue
            result.append(str(rel / f) if str(rel) != "." else f)
    return sorted(result)


def md_table(header: list[str], rows: list[list[str]]) -> str:
    lines = ["| " + " | ".join(header) + " |",
             "|" + "---|" * len(header)]
    for r in rows:
        lines.append("| " + " | ".join(str(c) for c in r) + " |")
    return "\n".join(lines)

