def resolve_test_target(test_file: str, fset: set[str]) -> str:
    base = test_file[:-3]
    if base.startswith("test_"):
        base = base[len("test_"):]
    for pattern in TEST_CANDIDATES:
        if pattern.format(n=base + ".py") in fset:
            return pattern.format(n=base + ".py")
    best = None
    for cand_file in fset:
        if cand_file == "tests/" + test_file or not cand_file.endswith(".py"):
            continue
        name = cand_file.rsplit("/", 1)[-1][:-3]
        if base.startswith(name) and name:
            if best is None or len(name) > len(best[0]):
                best = (name, cand_file)
    if best:
        return best[1]
    return "(integration/harness test)"


